#!/usr/bin/env node
import { readFile } from "node:fs/promises";
import { parseArgs } from "node:util";

import { emitGeneratedFile, finishCheck, repositoryPath } from "./lib/generated-file.mjs";

/**
 * Record the licence of every package that ends up in the tarball.
 *
 * Scoped to the **production** closure, not the whole tree. `uvp` ships compiled
 * JavaScript and no bundler, so what a user installs is `dependencies` and
 * whatever those need — 300-odd devDependencies are build tools that never reach
 * anyone. Recording them would triple the size of this file and bury the handful
 * of licences that actually matter.
 *
 * Read from `package-lock.json` rather than from `node_modules`, because the
 * lockfile is the artifact that was reviewed and committed. A tree that has been
 * `npm install`ed differently on two machines would otherwise produce two
 * different licence records.
 *
 * This is a data file, not a legal notice. THIRD_PARTY_NOTICES.md is written by a
 * person and cites this; generating prose would produce a document nobody read.
 */

const OUTPUT = "licenses/npm-dependencies.json";

const { values } = parseArgs({
  options: {
    check: { type: "boolean", default: false },
    help: { type: "boolean", default: false },
  },
  allowPositionals: false,
});

if (values.help) {
  console.log(`Usage: node scripts/licenses.mjs [--check]

Writes ${OUTPUT} with the production dependency closure from package-lock.json.
--check  fail when the file on disk differs, without writing.`);
  process.exit(0);
}

const lock = JSON.parse(await readFile(repositoryPath("package-lock.json"), "utf8"));
const packages = lock.packages ?? {};

if (Object.keys(packages).length === 0) {
  console.error("package-lock.json has no `packages` map; it predates lockfileVersion 2.");
  console.error("Run `npm install` to regenerate it.");
  process.exit(2);
}

/**
 * Resolve a dependency name from a location in the tree.
 *
 * npm hoists aggressively, so the root `node_modules` answers almost every
 * lookup; the upward walk handles the cases it does not, including a nested copy
 * that exists because of a version conflict.
 */
const resolve = (fromPath, name) => {
  let current = fromPath;
  for (;;) {
    const candidate = current === "" ? `node_modules/${name}` : `${current}/node_modules/${name}`;
    if (packages[candidate] !== undefined) return candidate;
    if (current === "") return undefined;
    const cut = current.lastIndexOf("/node_modules/");
    current = cut === -1 ? "" : current.slice(0, cut);
  }
};

const rootDependencies = Object.keys(packages[""]?.dependencies ?? {});
const optionalDependencies = new Set(Object.keys(packages[""]?.optionalDependencies ?? {}));

const seen = new Map();
const queue = rootDependencies.map((name) => ({ name, from: "" }));
const unresolved = [];

while (queue.length > 0) {
  const { name, from } = queue.shift();
  const resolved = resolve(from, name);
  if (resolved === undefined) {
    unresolved.push(name);
    continue;
  }
  if (seen.has(resolved)) continue;

  const entry = packages[resolved];
  seen.set(resolved, {
    name,
    version: entry.version ?? null,
    license: typeof entry.license === "string" ? entry.license : null,
    direct: from === "",
    optional: optionalDependencies.has(name),
    resolved_from: entry.resolved ?? null,
  });

  for (const nested of Object.keys(entry.dependencies ?? {})) {
    queue.push({ name: nested, from: resolved });
  }
}

if (unresolved.length > 0) {
  console.error(`Could not resolve ${unresolved.length} package(s): ${unresolved.join(", ")}`);
  console.error("The lockfile and the dependency graph disagree; run `npm install` and retry.");
  process.exit(2);
}

const entries = [...seen.values()].sort((left, right) =>
  left.name < right.name ? -1 : left.name > right.name ? 1 : 0,
);

const withoutLicense = entries.filter((entry) => entry.license === null);

const document = {
  package: lock.name,
  lockfileVersion: lock.lockfileVersion,
  note: "Generated by scripts/licenses.mjs from package-lock.json. Production closure only. Not a legal notice.",
  count: entries.length,
  direct_count: entries.filter((entry) => entry.direct).length,
  packages: entries,
};

const contents = `${JSON.stringify(document, null, 2)}\n`;

const result = await emitGeneratedFile({ relative: OUTPUT, contents, check: values.check });

if (values.check) process.exit(finishCheck([result], { label: "dependency licences" }));

console.log(`wrote ${OUTPUT} (${entries.length} package(s), ${document.direct_count} direct)`);
if (withoutLicense.length > 0) {
  console.warn(
    `warning: ${withoutLicense.length} package(s) declare no licence: ` +
      withoutLicense.map((entry) => entry.name).join(", "),
  );
}
