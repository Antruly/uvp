import { UVP_FRONTEND_DEFINITIONS, type UvpFrontend } from "../domain/frontends.js";

/**
 * The built-in static skins, generated as plain files.
 *
 * A skin is three files under `public/<id>/` — `index.html`, `app.css`, and
 * `app.js` — and nothing else. They are deliberately not a framework build:
 * the workspace must still be an ordinary CMake project, and a frontend that
 * needed Node would make `uvp build` depend on a toolchain the generated
 * project does not name.
 *
 * Every page is self-contained and same-origin. No page fetches a server route,
 * so each one loads on a template that does not serve that route, and none of
 * them names a CDN, an external font, or an analytics endpoint. The JavaScript
 * only renders values the browser already has (the clock and the viewport), so
 * the pages are honest about not having contacted the service.
 */
export interface FrontendFile {
  readonly path: string;
  readonly content: string;
}

/** The directory a skin is served from, relative to the workspace root. */
export const frontendDirectory = (frontend: UvpFrontend): string => `public/${frontend}`;

/**
 * The files one skin contributes.
 *
 * Asset links are relative (`app.css`, `app.js`) so the skin works at
 * `/<id>/` without the generator knowing the port or the host.
 */
export const frontendFiles = (frontend: UvpFrontend, name: string): readonly FrontendFile[] => {
  const directory = frontendDirectory(frontend);
  return [
    { path: `${directory}/index.html`, content: skinPage(frontend, name) },
    { path: `${directory}/app.css`, content: SKIN_STYLES[frontend] },
    { path: `${directory}/app.js`, content: SKIN_SCRIPTS[frontend] },
  ];
};

const page = (title: string, body: string): string => `<!doctype html>
<html lang="en">
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${title}</title>
<link rel="stylesheet" href="app.css">
${body}
</html>
`;

/**
 * The page each skin serves.
 *
 * The markup keeps the heading and the local facts in real elements rather than
 * writing them from script, so the page still reads with JavaScript disabled;
 * the status lines the script fills start as a dash rather than a claim.
 */
const skinPage = (frontend: UvpFrontend, name: string): string => {
  switch (frontend) {
    case "h5-minimal":
      return page(
        `${name} — minimal`,
        `<main>
  <h1>${name}</h1>
  <p>This page was generated by uvp and is served by your libuvcpp service.</p>
  <p class="status" id="status">—</p>
</main>
<noscript><p class="status">Local time needs JavaScript; everything else on this page works without it.</p></noscript>
<script src="app.js" defer></script>`,
      );
    case "h5-dashboard":
      return page(
        `${name} — dashboard`,
        `<header>
  <h1>${name}</h1>
  <p class="dim">A static dashboard skin. Every value below is rendered locally.</p>
</header>
<section class="grid">
  <article class="card"><h2>Local time</h2><p id="clock">—</p></article>
  <article class="card"><h2>Viewport</h2><p id="viewport">—</p></article>
  <article class="card"><h2>Time on page</h2><p id="uptime">—</p></article>
  <article class="card"><h2>Assets</h2><p>Local only</p></article>
</section>
<footer>No CDN, no external font, no request leaves this origin.</footer>
<noscript><p>The tiles above are filled by local JavaScript; nothing else on this page needs it.</p></noscript>
<script src="app.js" defer></script>`,
      );
    case "h5-tech":
      return page(
        `${name} — tech`,
        `<header>
  <h1>${name}</h1>
  <p class="dim">uvp static skin · h5-tech</p>
</header>
<pre id="log"></pre>
<noscript><p>The render log needs local JavaScript; this page contacts nothing either way.</p></noscript>
<script src="app.js" defer></script>`,
      );
  }
};

