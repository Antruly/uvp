const TECH_JS = `(() => {
  const log = document.getElementById('log');
  const line = (text) => {
    const entry = document.createElement('div');
    entry.className = 'line';
    entry.textContent = text;
    log.append(entry);
    return entry;
  };
  line('boot: static page loaded');
  line('env: viewport ' + window.innerWidth + '×' + window.innerHeight);
  line('net: no external requests issued by this page');
  const clock = line('clock: —');
  const render = () => { clock.textContent = 'clock: ' + new Date().toLocaleTimeString(); };
  render();
  window.setInterval(render, 1000);
})();
`;

const SKIN_STYLES: Readonly<Record<UvpFrontend, string>> = {
  "h5-minimal": MINIMAL_CSS,
  "h5-dashboard": DASHBOARD_CSS,
  "h5-tech": TECH_CSS,
};

/** One script per skin. None of them issues a request, so the pages work offline. */
const SKIN_SCRIPTS: Readonly<Record<UvpFrontend, string>> = {
  "h5-minimal": MINIMAL_JS,
  "h5-dashboard": DASHBOARD_JS,
  "h5-tech": TECH_JS,
};

/**
 * The page that lists the selected skins.
 *
 * Written only where the template does not already own `public/index.html` — a
 * `static-files` placeholder or a `websocket-test` console stays the document
 * at `/`, and those pages link the skins themselves. Inline styles and no script
 * keep the selector one file, so a workspace with skins has no asset the page
 * forgot to list.
 */
export const frontendSelector = (frontends: readonly UvpFrontend[], name: string): string => {
  const items = frontends
    .map(
      (frontend) =>
        `    <li><a href="./${frontend}/">${frontend}</a><span>${UVP_FRONTEND_DEFINITIONS[frontend].description}</span></li>`,
    )
    .join("\n");
  return `<!doctype html>
<html lang="en">
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${name} — frontends</title>
<style>
  :root { color-scheme: light; --ink: #17181c; --muted: #5b6270; --line: #dfe3ea; }
  * { box-sizing: border-box; }
  body { margin: 0; background: #f6f7f9; color: var(--ink); font: 16px/1.55 system-ui, sans-serif; }
  main { max-width: 44rem; margin: 0 auto; padding: 3rem 1rem; }
  h1 { margin: 0 0 .5rem; font-size: clamp(1.5rem, 6vw, 2.25rem); overflow-wrap: anywhere; }
  p { margin: 0 0 1rem; }
  ul { list-style: none; margin: 0; padding: 0; display: grid; gap: .75rem; }
  li { background: #fff; border: 1px solid var(--line); border-radius: .75rem; padding: 1rem; }
  a { color: #0b62d6; font-weight: 600; text-decoration: none; }
  a:focus-visible, a:hover { text-decoration: underline; }
  span { display: block; color: var(--muted); margin-top: .25rem; }
</style>
<main>
  <h1>${name}</h1>
  <p>This workspace serves ${frontends.length === 1 ? "one static frontend" : `${String(frontends.length)} static frontends`}.
  Each page is a directory of local files; none of them loads a CDN, an external font, or a remote script.</p>
  <ul>
${items}
  </ul>
  <p>Generated by uvp. The pages are static: the service does not render them.</p>
</main>
</html>
`;
};
