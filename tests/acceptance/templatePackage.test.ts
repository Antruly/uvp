import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";

import { afterAll, describe, expect, it } from "vitest";

import { EXIT_OK } from "../../src/cli/exitCodes.js";
import { renderTemplate } from "../../src/application/templates.js";
import {
  cleanup,
  realLibuvcpp,
  resultOrThrow,
  runCli,
  scratch,
  skipReason,
} from "../support/realLibuvcpp.js";

/**
 * A workspace rendered from a stored package, built and verified for real.
 *
 * The unit lane proves the substitution and the manifest merge; the CLI
 * boundary proves the refusals and the error contract. Neither can answer the
 * question this file exists for: when the package's bytes are what uvp writes,
 * does the resulting project still build against libuvcpp, start, and answer on
 * the wire?
 *
 * The package here is built from the `hello-http` template's rendered files, so
 * the source is a realistic CMake project rather than a toy. That is deliberate:
 * a hand-written "minimal" package could pass while hiding a rendering defect
 * that a real tree exposes, and it would replace one fixture with another of the
 * same kind. What the package adds is the identity the workspace has to carry —
 * `template_package` with the digest — and the route declaration that
 * `uvp init` reports instead of guessing.
 *
 * Skip-with-a-reason applies as in the other acceptance lanes: without a
 * libuvcpp install there is nothing to compile, and reporting that as a failure
 * would report the host as a uvp defect.
 */

/** This file's port. Disjoint from manualPath's 8321, http2's 8322, and tls's 8331. */
const PORT = 8351;

const PACKAGE_ID = "hello-package";
const PACKAGE_VERSION = "1.0.0";

const digestOf = (bytes: Uint8Array): string =>
  `sha256:${createHash("sha256").update(bytes).digest("hex")}`;

/**
 * Write the `hello-http` files as a `uvp.template/1` package.
 *
 * The manifest is written here rather than generated by a uvp function: the
 * package format is data an author produces with any editor, and a test that
 * used uvp's own writer would not prove the reader accepts an independently
 * written one. Only the file contents come from `renderTemplate`.
 */
const writePackage = async (root: string): Promise<string> => {
  const dir = join(root, "package");
  const files = renderTemplate("hello-http", {
    name: "svc",
    port: PORT,
    features: ["websocket"],
  });
  const declared: { path: string; digest: string; bytes: number }[] = [];
  for (const file of files) {
    const bytes = Buffer.from(file.content, "utf8");
    await mkdir(dirname(join(dir, "files", file.path)), { recursive: true });
    await writeFile(join(dir, "files", file.path), bytes);
    declared.push({ path: file.path, digest: digestOf(bytes), bytes: bytes.byteLength });
  }
  await writeFile(
    join(dir, "template.json"),
    JSON.stringify({
      schema: "uvp.template/1",
      id: PACKAGE_ID,
      version: PACKAGE_VERSION,
      name: "Hello package",
      description: "The hello-http source, packaged",
      category: "backend",
      requires: { features: ["websocket"] },
      routes: ["GET /hello"],
      files: declared,
      license: { spdx: "MIT", file: "LICENSE" },
      provenance: { author: "uvp tests", createdAt: "2026-10-19T00:00:00Z" },
    }),
  );
  await writeFile(join(dir, "README.md"), "# Hello package\n");
  await writeFile(join(dir, "LICENSE"), "MIT\n");
  return dir;
};

afterAll(() => {
  cleanup();
});

describe.skipIf(realLibuvcpp === undefined)(
  realLibuvcpp === undefined
    ? `a workspace from a stored template package — skipped: ${skipReason}`
    : `a workspace from a stored template package, on real CMake and libuvcpp ${realLibuvcpp.version}`,
  () => {
    it("renders, builds, starts, and verifies a package workspace", async () => {
      const root = scratch();
      const store = join(root, "store");
      const env = { UVP_TEMPLATE_HOME: store };
      const source = await writePackage(root);

      const imported = await runCli(["template", "import", source, "--json"], { env });
      expect(imported.exit, imported.stderr).toBe(EXIT_OK);
      const packageDigest = resultOrThrow(imported)["digest"];

      const target = join(root, "package-workspace");
      const initialized = await runCli(
        [
          "init",
          target,
          "--name",
          "svc",
          "--template-package",
          `${PACKAGE_ID}@${PACKAGE_VERSION}`,
          "--port",
          String(PORT),
          "--json",
        ],
        { env },
      );
      expect(initialized.exit, initialized.stderr).toBe(EXIT_OK);
      const created = resultOrThrow(initialized);

      // The workspace says where it came from, and does not also name the
      // built-in template the package's uvp.json used to carry.
      expect(created["template"]).toBeUndefined();
      expect(created["template_package"]).toEqual({
        id: PACKAGE_ID,
        version: PACKAGE_VERSION,
        digest: packageDigest,
      });
      // Declared, not inferred from the source uvp never executed.
      expect(created["routes"]).toEqual(["GET /hello"]);

      const verified = await runCli(
        [
          "verify",
          target,
          "--port",
          String(PORT),
          // `hello-http` registers `/hello`, not `/`: readiness has to ask a
          // path the generated service actually serves.
          "--ready-path",
          "/hello",
          "--request",
          "GET",
          "/hello",
          "--assert",
          "status=200",
          "--json",
        ],
        { env },
      );
      expect(verified.exit, verified.stderr || verified.stdout.slice(0, 800)).toBe(EXIT_OK);
      const result = resultOrThrow(verified);
      expect(result["status"]).toBe("verified");
      // The render did not cost the workspace its build: this is a real
      // configure and compile of the package's files.
      const build = result["build"] as Record<string, unknown>;
      expect(build["succeeded"]).toBe(true);
    }, 600_000);
  },
);
