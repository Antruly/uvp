import { spawn } from "node:child_process";
import { createServer } from "node:net";
import { fileURLToPath } from "node:url";

/**
 * Starting and stopping the conformance target.
 *
 * Two ways to get a port, and both are needed. `freePort` reserves a number so a
 * *child* process can be told where to listen before it starts — which is what
 * `uvp_run` needs, since its readiness probe is aimed at the port before the
 * binary exists. `startFixture` runs the fixture in-process for the web tools,
 * which need a target that is already up.
 *
 * The port reservation is a bind-then-release, so in principle another process
 * can take the number in the gap. The window is microseconds and the failure is
 * a clear `EADDRINUSE` rather than a wrong answer, which is the trade a test can
 * afford; a fixed port number would instead collide with whatever else is on the
 * machine.
 */

export const FIXTURE_SCRIPT = fileURLToPath(
  new URL("./fixtures/fixtureServer.mjs", import.meta.url),
);

export const freePort = async (): Promise<number> =>
  await new Promise((resolve, reject) => {
    const probe = createServer();
    probe.on("error", reject);
    probe.listen(0, "127.0.0.1", () => {
      const address = probe.address();
      if (address === null || typeof address === "string") {
        probe.close();
        reject(new Error("the port probe did not return a numeric address"));
        return;
      }
      const { port } = address;
      probe.close(() => resolve(port));
    });
  });

export interface FixtureServer {
  readonly port: number;
  readonly origin: string;
  stop(): Promise<void>;
}

/** Run the fixture for the duration of a test, on a reserved port. */
export const startFixture = async (): Promise<FixtureServer> => {
  const port = await freePort();
  const child = spawn(process.execPath, [FIXTURE_SCRIPT, String(port)], {
    stdio: ["ignore", "pipe", "pipe"],
    env: { ...process.env, FIXTURE_PORT: String(port) },
  });

  await new Promise<void>((resolve, reject) => {
    const timer = setTimeout(
      () => reject(new Error("the fixture did not start within 10s")),
      10_000,
    );
    const settle = (): void => {
      clearTimeout(timer);
      resolve();
    };
    child.stdout.setEncoding("utf8");
    child.stdout.on("data", (chunk: string) => {
      if (chunk.includes("fixture listening")) settle();
    });
    child.once("exit", (code) => {
      clearTimeout(timer);
      reject(new Error(`the fixture exited during startup with code ${String(code)}`));
    });
    child.once("error", (cause) => {
      clearTimeout(timer);
      reject(cause);
    });
  });

  return {
    port,
    origin: `http://127.0.0.1:${String(port)}`,
    stop: async () => {
      if (child.exitCode !== null || child.signalCode !== null) return;
      const exited = new Promise<void>((resolve) => child.once("exit", () => resolve()));
      child.kill("SIGTERM");
      // The fixture closes its listener and exits, but a socket held open by a
      // failed test would keep it alive; kill it rather than hang the suite.
      const deadline = setTimeout(() => child.kill("SIGKILL"), 3_000);
      await exited;
      clearTimeout(deadline);
    },
  };
};

/**
 * A shell script that starts the fixture, installed as a workspace's binary.
 *
 * Written where `uvp_run` looks for one — `<workspace>/build/<manifest.binary>` —
 * so launching it goes through exactly the path a compiled service does:
 * spawn, supervise, probe the port, report. The port arrives through the
 * environment rather than from the manifest, because the fixture takes its port
 * as an argument and the manifest's value belongs to the generated C++.
 */
export const fixtureBinaryScript = (port: number): string =>
  [
    "#!/bin/sh",
    "# Generated by the uvp conformance lane, not by uvp.",
    `exec ${process.execPath} ${JSON.stringify(FIXTURE_SCRIPT)} ${String(port)}`,
    "",
  ].join("\n");
